import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

export interface RegistryOptions {
  kitsDir: string;
  booksDir: string;
  mode: "write" | "check";
}

export interface GeneratedFile {
  filePath: string;
  content: string;
}

const BANNER = "// Auto-generated by scripts/generate-solutions-registry.ts; do not edit manually.";

function toCamel(slug: string): string {
  return slug.replace(/[^a-zA-Z0-9]+([a-zA-Z0-9])/g, (_, ch: string) => ch.toUpperCase()).replace(/[^a-zA-Z0-9]/g, "");
}

function toPascal(slug: string): string {
  const camel = toCamel(slug);
  return camel ? camel[0].toUpperCase() + camel.slice(1) : "Item";
}

function toPosixImport(fromFile: string, targetFileNoExt: string): string {
  const rel = path.relative(path.dirname(fromFile), targetFileNoExt).split(path.sep).join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

function parseSource(filePath: string): ts.SourceFile {
  const kind = filePath.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  return ts.createSourceFile(filePath, fs.readFileSync(filePath, "utf8"), ts.ScriptTarget.Latest, true, kind);
}

function exportedSymbols(filePath: string): { named: string[]; hasDefault: boolean } {
  const source = parseSource(filePath);
  const named: string[] = [];
  let hasDefault = false;

  const isExported = (node: ts.Node) =>
    ts.canHaveModifiers(node) &&
    Boolean(ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword));

  const isDefault = (node: ts.Node) =>
    ts.canHaveModifiers(node) &&
    Boolean(ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword));

  source.forEachChild((node) => {
    if (ts.isExportAssignment(node) && !node.isExportEquals) {
      hasDefault = true;
      return;
    }
    if (ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node)) {
      if (isDefault(node)) hasDefault = true;
      if (isExported(node) && node.name) named.push(node.name.text);
      return;
    }
    if (ts.isVariableStatement(node) && isExported(node)) {
      for (const decl of node.declarationList.declarations) {
        if (ts.isIdentifier(decl.name)) named.push(decl.name.text);
      }
      return;
    }
    if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause)) {
      for (const spec of node.exportClause.elements) {
        if (spec.name.text === "default") hasDefault = true;
        else named.push(spec.name.text);
      }
    }
  });

  return { named, hasDefault };
}

function pickKitSymbol(filePath: string, kitId: string): string {
  const { named } = exportedSymbols(filePath);
  const preferred = `${toCamel(kitId)}Kit`;
  if (named.includes(preferred)) return preferred;
  const fallback = named.find((name) => name.endsWith("Kit"));
  if (!fallback) {
    throw new Error(`${filePath}: expected an exported kit definition ending in "Kit" (e.g. "${preferred}")`);
  }
  return fallback;
}

function pickPosterSymbol(filePath: string, kitId: string): string {
  const { named } = exportedSymbols(filePath);
  const preferred = `${toPascal(kitId)}Poster`;
  if (named.includes(preferred)) return preferred;
  const fallback = named.find((name) => name.endsWith("Poster"));
  if (!fallback) {
    throw new Error(`${filePath}: expected an exported poster component ending in "Poster" (e.g. "${preferred}")`);
  }
  return fallback;
}

function assertDefaultExport(filePath: string): void {
  const { hasDefault } = exportedSymbols(filePath);
  if (!hasDefault) {
    throw new Error(`${filePath}: expected a default React component export`);
  }
}

function discoverDirs(parentDir: string): string[] {
  if (!fs.existsSync(parentDir)) return [];
  return fs
    .readdirSync(parentDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, "en"));
}

function walkTsFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  const results: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkTsFiles(full));
    } else if (entry.isFile() && entry.name.endsWith(".ts") && !entry.name.endsWith(".d.ts") && entry.name !== "index.ts") {
      results.push(full);
    }
  }
  return results.sort((a, b) => a.localeCompare(b, "en"));
}

export function buildGeneratedFiles({ kitsDir, booksDir }: Pick<RegistryOptions, "kitsDir" | "booksDir">): GeneratedFile[] {
  const generated: GeneratedFile[] = [];

  const kits = discoverDirs(kitsDir)
    .filter((kitId) => fs.existsSync(path.join(kitsDir, kitId, "model.ts")))
    .map((kitId) => {
      const modelFile = path.join(kitsDir, kitId, "model.ts");
      const posterFile = path.join(kitsDir, kitId, "Poster.tsx");
      const benchFile = path.join(kitsDir, kitId, "Bench.tsx");
      const kitSymbol = pickKitSymbol(modelFile, kitId);
      const posterSymbol = fs.existsSync(posterFile) ? pickPosterSymbol(posterFile, kitId) : undefined;
      const hasBench = fs.existsSync(benchFile);
      if (hasBench) assertDefaultExport(benchFile);
      return { kitId, kitSymbol, posterSymbol, hasBench };
    });

  const modelsContent = [
    BANNER,
    ...kits.map((k) => `import { ${k.kitSymbol} } from "./${k.kitId}/model";`),
    `import type { KitDefinition } from "@scifunlab/solution-sdk/kit";`,
    "",
    "/**",
    " * Pure kit definitions (models, object names, labels). Safe to import on the",
    " * server and the client. Scenes and posters live in separate registries so",
    " * three.js never reaches a server page and SVG posters never reach the client.",
    " */",
    "const registeredKits = {",
    ...kits.map((k) => `  ${JSON.stringify(k.kitId)}: ${k.kitSymbol} as unknown as KitDefinition,`),
    "};",
    "",
    "export type RegisteredKitId = keyof typeof registeredKits;",
    "",
    "export const kitDefinitions: Partial<Record<RegisteredKitId, KitDefinition>> = registeredKits;",
    "",
  ].join("\n");

  const benchesContent = [
    `"use client";`,
    "",
    BANNER,
    `import { lazy, type ComponentType, type LazyExoticComponent } from "react";`,
    "",
    `import type { BenchProps } from "@scifunlab/solution-sdk/kit";`,
    "",
    `import type { RegisteredKitId } from "./models";`,
    "",
    "/** Lazily loaded 3D benches, one per kit, each in its own client chunk. */",
    "export const kitBenches: Partial<Record<RegisteredKitId, LazyExoticComponent<ComponentType<BenchProps>>>> = {",
    ...kits.filter((k) => k.hasBench).map((k) => `  ${JSON.stringify(k.kitId)}: lazy(() => import("./${k.kitId}/Bench")),`),
    "};",
    "",
  ].join("\n");

  const postersContent = [
    BANNER,
    `import type { ComponentType } from "react";`,
    "",
    `import type { KitPosterProps } from "@scifunlab/solution-sdk/kit";`,
    "",
    ...kits.filter((k) => k.posterSymbol).map((k) => `import { ${k.posterSymbol} } from "./${k.kitId}/Poster";`),
    `import type { RegisteredKitId } from "./models";`,
    "",
    "/** Server-rendered SVG posters, one per kit. Never imported by client code. */",
    "export const kitPosters: Partial<Record<RegisteredKitId, ComponentType<KitPosterProps>>> = {",
    ...kits.filter((k) => k.posterSymbol).map((k) => `  ${JSON.stringify(k.kitId)}: ${k.posterSymbol},`),
    "};",
    "",
  ].join("\n");

  generated.push(
    { filePath: path.join(kitsDir, "models.ts"), content: modelsContent },
    { filePath: path.join(kitsDir, "benches.ts"), content: benchesContent },
    { filePath: path.join(kitsDir, "posters.tsx"), content: postersContent },
  );

  const books = discoverDirs(booksDir)
    .filter((bookId) => fs.existsSync(path.join(booksDir, bookId, "book.ts")))
    .map((bookId) => {
      const bookFile = path.join(booksDir, bookId, "book.ts");
      assertDefaultExport(bookFile);
      const solutionsRoot = path.join(booksDir, bookId, "solutions");
      const solutionFiles = walkTsFiles(solutionsRoot);
      for (const file of solutionFiles) assertDefaultExport(file);
      return { bookId, varName: toCamel(bookId), solutionFiles, indexPath: path.join(solutionsRoot, "index.ts") };
    });

  for (const book of books) {
    const items = book.solutionFiles.map((file, idx) => ({
      ident: `solution_${idx}_${toCamel(path.basename(file, ".ts"))}`,
      importPath: toPosixImport(book.indexPath, file.slice(0, -3)),
    }));
    const indexContent = [
      BANNER,
      `import type { Solution } from "@scifunlab/solution-sdk";`,
      "",
      ...items.map((item) => `import ${item.ident} from "${item.importPath}";`),
      "",
      `export const solutionModules: Solution[] = [${items.map((i) => i.ident).join(", ")}];`,
      "",
    ].join("\n");
    generated.push({ filePath: book.indexPath, content: indexContent });
  }

  const catalogContent = [
    BANNER,
    `import type { BookDefinition } from "@scifunlab/solution-sdk";`,
    "",
    ...books.map((b) => `import ${b.varName}Book from "./${b.bookId}/book";`),
    "",
    `export const allBookCatalog: readonly BookDefinition[] = [${books.map((b) => `${b.varName}Book`).join(", ")}];`,
    "",
    "export const bookCatalogById: Record<string, BookDefinition> = {",
    ...books.map((b) => `  ${JSON.stringify(b.bookId)}: ${b.varName}Book,`),
    "};",
    "",
  ].join("\n");

  const solutionsContent = [
    BANNER,
    `import type { Solution } from "@scifunlab/solution-sdk";`,
    "",
    ...books.map((b) => `import { solutionModules as ${b.varName}Solutions } from "./${b.bookId}/solutions";`),
    "",
    `export const allBookSolutions: Solution[] = [${books.map((b) => `...${b.varName}Solutions`).join(", ")}];`,
    "",
  ].join("\n");

  generated.push(
    { filePath: path.join(booksDir, "catalog.ts"), content: catalogContent },
    { filePath: path.join(booksDir, "solutions.ts"), content: solutionsContent },
  );

  return generated;
}

export function runSolutionsRegistry(options: RegistryOptions): { updated: string[]; stale: string[] } {
  const files = buildGeneratedFiles(options);
  const updated: string[] = [];
  const stale: string[] = [];

  for (const { filePath, content } of files) {
    const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
    if (existing === content) continue;
    if (options.mode === "check") {
      stale.push(filePath);
    } else {
      fs.mkdirSync(path.dirname(filePath), { recursive: true });
      fs.writeFileSync(filePath, content, "utf8");
      updated.push(filePath);
    }
  }

  if (options.mode === "check" && stale.length > 0) {
    throw new Error(
      `Generated solution registries are out of date (${stale.length}):\n${stale.map((f) => `  - ${f}`).join("\n")}\nRun "npm run solutions:generate".`,
    );
  }

  return { updated, stale };
}

function parseCliArgs(argv: string[]): RegistryOptions {
  const mode = argv.includes("--check") ? "check" : "write";
  const kitsIdx = argv.indexOf("--kits-dir");
  const booksIdx = argv.indexOf("--books-dir");
  const defaultKits = fs.existsSync(path.resolve("lib/solutions/kits"))
    ? path.resolve("lib/solutions/kits")
    : path.resolve("kits");
  const defaultBooks = fs.existsSync(path.resolve("lib/solutions/books"))
    ? path.resolve("lib/solutions/books")
    : path.resolve("books");
  return {
    mode,
    kitsDir: kitsIdx !== -1 && argv[kitsIdx + 1] ? path.resolve(argv[kitsIdx + 1]) : defaultKits,
    booksDir: booksIdx !== -1 && argv[booksIdx + 1] ? path.resolve(argv[booksIdx + 1]) : defaultBooks,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseCliArgs(process.argv.slice(2));
  const { updated } = runSolutionsRegistry(opts);
  if (opts.mode === "check") {
    console.log("OK: solution and kit registries are up to date");
  } else {
    console.log(updated.length ? `Updated ${updated.length} generated registry file(s)` : "Registries already up to date");
  }
}
